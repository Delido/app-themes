function tokenColors(v) {
  const t = (scope, foreground, fontStyle) => ({ scope, settings: fontStyle ? { foreground, fontStyle } : { foreground } });
  return [
    t(['comment', 'punctuation.definition.comment', 'string.comment'], DIM, 'italic'),
    t(['keyword', 'storage.modifier', 'keyword.control', 'keyword.other.using', 'keyword.other.import'], v.light),
    t(['storage.type', 'keyword.declaration', 'storage.type.function'], v.b),
    t(['keyword.operator', 'punctuation', 'meta.brace', 'punctuation.separator', 'punctuation.terminator'], MUTED),
    t(['entity.name.function', 'support.function', 'meta.function-call.generic', 'variable.function'], '#7dd3fc'),
    t(['entity.name.type', 'entity.name.class', 'support.class', 'support.type', 'entity.other.inherited-class', 'entity.name.namespace'], '#c4b5fd'),
    t(['string', 'string.quoted', 'string.template', 'punctuation.definition.string'], '#86efac'),
    t(['string.regexp', 'constant.character.escape'], '#f9a8d4'),
    t(['constant.numeric', 'constant.language.boolean'], WARN),
    t(['constant.language', 'constant.other', 'variable.other.constant', 'support.constant'], '#fb7185'),
    t(['variable', 'variable.other.readwrite', 'meta.definition.variable'], FG),
    t(['variable.parameter', 'meta.parameter'], '#d8dbe5', 'italic'),
    t(['variable.language.this', 'variable.language.self', 'variable.language.super'], v.light, 'italic'),
    t(['variable.other.property', 'support.variable.property', 'meta.object-literal.key', 'variable.other.object.property'], '#a5b4fc'),
    t(['entity.name.tag', 'punctuation.definition.tag'], v.light),
    t(['entity.other.attribute-name'], v.b, 'italic'),
    t(['entity.name.decorator', 'meta.decorator', 'punctuation.decorator'], '#f9a8d4'),
    t(['markup.heading', 'entity.name.section'], v.light, 'bold'),
    t(['markup.bold'], FG_STRONG, 'bold'),
    t(['markup.italic'], FG, 'italic'),
    t(['markup.underline.link', 'markup.link'], v.b),
    t(['markup.inline.raw', 'markup.fenced_code'], '#86efac'),
    t(['markup.inserted'], OK),
    t(['markup.deleted'], '#fb7185'),
    t(['markup.changed'], v.light),
    t(['support.type.property-name.json', 'support.type.property-name'], '#a5b4fc'),
    t(['invalid', 'invalid.illegal'], ERR),
  ];
}

const semantic = v => ({
  'namespace': '#c4b5fd',
  'class': '#c4b5fd',
  'interface': { foreground: '#c4b5fd', italic: true },
  'enum': '#c4b5fd',
  'type': '#c4b5fd',
  'typeParameter': { foreground: '#c4b5fd', italic: true },
  'function': '#7dd3fc',
  'method': '#7dd3fc',
  'property': '#a5b4fc',
  'enumMember': '#fb7185',
  'parameter': { foreground: '#d8dbe5', italic: true },
  'variable.readonly': '#fb7185',
  'variable.defaultLibrary': v.b,
  'keyword': v.light,
  'decorator': '#f9a8d4',
});

fs.mkdirSync(path.join(__dirname, 'themes'), { recursive: true });
for (const [id, v] of Object.entries(VARIANTS)) {
  const theme = {
    name: `Aurora ${v.name}`,
    type: 'dark',
    semanticHighlighting: true,
    colors: colors(v),
    tokenColors: tokenColors(v),
    semanticTokenColors: semantic(v),
  };
  fs.writeFileSync(path.join(__dirname, 'themes', `aurora-${id}-color-theme.json`), JSON.stringify(theme, null, 2) + '\n');
}
console.log(`${Object.keys(VARIANTS).length} Themes geschrieben.`);
